"""Generate the manuscript's numerical claims from its selected, validated suite."""
import csv
from pathlib import Path
from paper_data import data_paths

ROOT=Path(__file__).resolve().parents[1]


def rows(path):
    with path.open() as f: return list(csv.DictReader(f))


def span(values,places=0):
    low,high=min(values),max(values)
    return format(low,'.'+str(places)+'f') if abs(high-low)<1e-6 else format(low,'.'+str(places)+'f')+'--'+format(high,'.'+str(places)+'f')


def triple(values):
    a,b,c=values
    return '{:,}, {:,}, and {:,}'.format(a,b,c)


def main():
    data=data_paths()
    width=rows(data['width']);graph=rows(data['graph']);bandwidth=rows(data['bandwidth']);cache=rows(data['cache'])
    commands={}
    for n,label in ((8,'Eight'),(16,'Sixteen'),(24,'TwentyFour'),(32,'ThirtyTwo')):
        base=next(r for r in width if int(r['n'])==n and int(r['width'])==1)
        tiled=next(r for r in width if int(r['n'])==n and int(r['width'])==4)
        commands['Speedup'+label]='{:.3f}'.format(float(tiled['cpu_speedup']))
        commands['ProgramReduction'+label]='{:.3f}'.format(100*(1-float(tiled['whole_program_ticks'])/float(base['whole_program_ticks'])))
    benefits=['{:.3f}\\%'.format(float(next(r for r in bandwidth if int(r['width'])==4 and int(r['bandwidth'])==bw)['offload_reduction_pct'])) for bw in (1,2,4)]
    commands['IssueLimitBenefits']=benefits[0]+', '+benefits[1]+', and '+benefits[2]
    commands['CompletionResidualNs']=span([float(r['completion_ticks'])/float(r['sim_freq'])*1e9-float(r['datapath_cycles']) for r in bandwidth])
    commands['HostReturnNs']=span([float(r['return_segment_ticks'])/float(r['sim_freq'])*1e9 for r in bandwidth])
    commands['OffloadResidualUs']=span([float(r['offload_ticks'])/float(r['sim_freq'])*1e6-float(r['datapath_cycles'])/1000 for r in bandwidth],3)
    graph=sorted(graph,key=lambda r:int(r['width']))
    commands['IssueBlockedCycles']=triple([int(r['issue_blocked_cycles']) for r in graph])
    commands['QueueBlockedCycles']=triple([int(r['queue_full_cycles']) for r in graph])
    for key,name in (('after_connected_Mul.gemm_value','GraphProducts'),('after_connected_Add.gemm_value','GraphAdds'),
                     ('accepted_A_load','AcceptedALoads'),('accepted_B_load','AcceptedBLoads'),('accepted_C_store','AcceptedCStores')):
        values=[int(r[key]) for r in graph]
        if len(set(values))!=1: raise ValueError('Rewrite the graph claim for differing '+key)
        commands[name]='{:,}'.format(values[0])
    commands['DemandMisses']=span([float(r['ruby_demand_misses']) for r in cache])
    text='% Generated by scripts/build_paper_numbers.py from paper/experiment_data.json.\n'
    text+=''.join('\\newcommand{\\'+name+'}{'+value+'}\n' for name,value in commands.items())
    (ROOT/'paper/result_macros.tex').write_text(text)
    print(text)


if __name__=='__main__':main()
